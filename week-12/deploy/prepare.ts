/**
 * Builds everything the server needs into week-12/deploy/out/.
 *
 *   bun week-12/deploy/prepare.ts https://vault.203-0-113-10.sslip.io
 *
 * The argument is the public address of the site. The result:
 *
 *   out/
 *   ├── compose.yml        the stack (Caddy, API, PostgreSQL, SeaweedFS)
 *   ├── schema.sql         applied by PostgreSQL on its first start
 *   ├── .env               secrets, generated on the first run and then kept
 *   ├── api/               image: the API bundle + its Dockerfile
 *   └── web/               image: Caddy + Caddyfile + the built React app
 *
 * Copy out/ to the server and run `docker compose up -d --build` there.
 * Running this script again (after code changes) rebuilds api/ and web/
 * but never touches an existing .env: new secrets would lock you out of
 * your own database.
 */
import { cp, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { $ } from "bun";

const publicUrl = Bun.argv[2]?.replace(/\/$/, "");
if (!publicUrl || !/^https?:\/\/[^/]+$/.test(publicUrl)) {
  console.error("Usage: bun week-12/deploy/prepare.ts https://<your-host-name>");
  console.error("Example (no domain needed): https://vault.203-0-113-10.sslip.io");
  process.exit(1);
}

const deployDir = import.meta.dir;
const apiDir = path.join(deployDir, "..", "encrypted-file-vault-api");
const clientDir = path.join(deployDir, "..", "encrypted-file-vault-client");
const out = path.join(deployDir, "out");

console.log("1/3  Building the API bundle…");
await $`bun run build`.cwd(apiDir).quiet();

console.log(`2/3  Building the client for ${publicUrl}…`);
// The client calls the API at the same address: Caddy routes /api to it.
await $`bun run build`.cwd(clientDir).env({ ...process.env, BUN_PUBLIC_API_URL: publicUrl }).quiet();

console.log("3/3  Assembling deploy/out/…");
await rm(path.join(out, "api"), { recursive: true, force: true });
await rm(path.join(out, "web"), { recursive: true, force: true });
await mkdir(path.join(out, "api"), { recursive: true });

await cp(path.join(deployDir, "compose.yml"), path.join(out, "compose.yml"));
await cp(path.join(apiDir, "sql", "schema.sql"), path.join(out, "schema.sql"));
await cp(path.join(apiDir, "Dockerfile"), path.join(out, "api", "Dockerfile"));
await cp(path.join(apiDir, "dist"), path.join(out, "api", "dist"), { recursive: true });
await cp(path.join(deployDir, "web"), path.join(out, "web"), { recursive: true });
await cp(path.join(clientDir, "dist"), path.join(out, "web", "client"), { recursive: true });

const envFile = Bun.file(path.join(out, ".env"));
const random = (bytes: number) => crypto.getRandomValues(new Uint8Array(bytes)).toHex();

if (await envFile.exists()) {
  const current = /^PUBLIC_URL=(.*)$/m.exec(await envFile.text())?.[1];
  if (current !== publicUrl) {
    console.warn(`\n⚠️  out/.env has PUBLIC_URL=${current}. Edit it if the address changed.`);
  }
} else {
  await Bun.write(
    envFile,
    `# Generated by prepare.ts. Secret: never commit or share this file.

# The site's public address. Caddy gets an HTTPS certificate for its host name.
PUBLIC_URL=${publicUrl}

# Give this code to the people who may register.
INVITE_CODE=${random(4)}

POSTGRES_PASSWORD=${random(24)}
JWT_SECRET=${random(32)}

# Object storage. By default SeaweedFS runs on this server (the profile below).
# For Hetzner Object Storage / DigitalOcean Spaces: delete the COMPOSE_PROFILES
# line and set the provider's endpoint, bucket and keys (see the week 12 README).
COMPOSE_PROFILES=self-hosted-storage
S3_ENDPOINT=http://object-storage:8333
S3_BUCKET=encrypted-files
S3_ACCESS_KEY_ID=${random(10)}
S3_SECRET_ACCESS_KEY=${random(24)}
S3_REGION=us-east-1
S3_VIRTUAL_HOSTED_STYLE=false
`,
  );
  console.log("     Created out/.env with fresh secrets.");
}

console.log(`
Done. Copy the folder to your server and start it there:

  rsync -a --delete ${path.relative(process.cwd(), out)}/ root@<server-ip>:vault/
  ssh root@<server-ip> "cd vault && docker compose up -d --build"

The invitation code is in out/.env (INVITE_CODE).`);
