// The API contract shared by the image gallery API and its client.

// Metadata about one uploaded image, as returned by the API.
export interface UploadRecord {
  id: string; // UUID generated by the server
  filename: string; // the name of the file on the server: `${id}.${extension}`
  originalName: string; // the name of the file on the user's computer
  mimeType: string; // e.g. "image/png"
  size: number; // bytes
  uploadedAt: string; // ISO 8601 timestamp
  url: string; // path the image is served from, e.g. "/uploads/<filename>"
}

export type ApiSuccess<T> = { ok: true; data: T };
export type ApiFailure = { ok: false; error: { message: string } };
export type ApiResult<T> = ApiSuccess<T> | ApiFailure;
