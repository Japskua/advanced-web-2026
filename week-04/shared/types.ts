/**
 * The API contract shared by the back-end and the front-end.
 *
 * Both projects import these types (with `import type`, so nothing from this
 * file exists at runtime). If the API changes the shape of a response, the
 * client stops compiling, instead of silently showing "undefined" or
 * "Invalid Date" in the browser.
 *
 * Only types that travel over HTTP belong here. Types that are internal to one
 * side (for example the raw response of the external joke API) stay in that
 * project.
 */

// A joke fetched from JokeAPI, as returned by GET /api/joke.
export interface Joke {
  externalId: number; // JokeAPI's own id for the joke
  category: string;
  text: string;
  fetchedAt: string; // ISO 8601 timestamp, e.g. "2026-10-12T08:30:00.000Z"
}

// A joke stored by our API, as returned by GET/POST /api/saved.
export interface SavedJoke {
  id: string; // generated by our API (UUID)
  externalId: number;
  category: string;
  text: string;
  savedAt: string; // ISO 8601 timestamp
}

// Body of POST /api/saved. The server generates `id` and `savedAt` itself.
export type SaveJokeBody = Pick<Joke, "externalId" | "category" | "text">;

// The response envelope (introduced in week 2).
export type ApiSuccess<T> = { ok: true; data: T };
export type ApiFailure = { ok: false; error: { message: string } };
export type ApiResult<T> = ApiSuccess<T> | ApiFailure;
